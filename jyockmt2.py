def recArea(base,height):
    recArea = base * height
    return recArea

print ("This code will calculate the area of a rectangle given base and height.")

basIn = int(input("Please enter the base of your rectangle: "))

hgtIn = int(input("Please enter the height of your rectangle: "))

yourArea = recArea(basIn,hgtIn)

print ("The area of your rectangle is", yourArea, "units.")














